//! Regression test for R2.1: App launching outside daemon sandbox via systemd transient unit.
//!
//! Verifies that launched applications do NOT inherit the daemon's sandbox properties:
//! - Seccomp filter: 0 (not 2 from @system-service)
//! - NoNewPrivs: 0 (not 1)
//! - Umask: not daemon's 0077 (user manager's 0002/0022)
//! - PPid: systemd user manager (not the daemon PID)
//! - Child process survives termination of daemon.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::sync::Arc;
use std::time::Duration;
use tempfile::tempdir;

use kynex_daemon::services::apps::{AppsServer, AppsSharedState};
use kynex_ipc::apps::Apps1Proxy;

#[tokio::test]
async fn test_app_launch_via_systemd_transient_unit_sandbox_isolation() {
    let server_conn = match zbus::Connection::session().await {
        Ok(c) => c,
        Err(e) => {
            eprintln!("Skipping systemd transient unit test: cannot connect to session bus: {e}");
            return;
        }
    };

    let client_conn = match zbus::Connection::session().await {
        Ok(c) => c,
        Err(e) => {
            eprintln!(
                "Skipping systemd transient unit test: cannot connect client to session bus: {e}"
            );
            return;
        }
    };

    let tmp = tempdir().unwrap();
    let app_dir = tmp.path().join("applications");
    fs::create_dir_all(&app_dir).unwrap();

    let dump_file = tmp.path().join("sandbox_dump.txt");
    let script_path = tmp.path().join("fake_sandboxed_runner.sh");
    let script_content = format!(
        r#"#!/usr/bin/env bash
status_file="/proc/$$/status"
grep -E '^(Seccomp|NoNewPrivs|PPid|Umask):' "$status_file" > "{dump}"
echo "PID: $$" >> "{dump}"
sleep 15
"#,
        dump = dump_file.display()
    );
    fs::write(&script_path, script_content).unwrap();
    fs::set_permissions(&script_path, fs::Permissions::from_mode(0o755)).unwrap();

    let desktop_content = format!(
        r#"[Desktop Entry]
Type=Application
Name=Sandbox Test App
Exec={script}
"#,
        script = script_path.display()
    );
    fs::write(app_dir.join("sandbox-test.desktop"), desktop_content).unwrap();

    let shared = Arc::new(AppsSharedState::new(vec![app_dir.clone()], "Kynex"));
    shared.reload().await;
    let server = AppsServer::new(Arc::clone(&shared));

    // Register on the session bus with a unique test path to avoid conflicts
    let test_path = "/org/kynexos/Daemon/Apps1TestSandbox";
    server_conn
        .object_server()
        .at(test_path, server)
        .await
        .expect("Serve AppsServer");

    let server_dest = server_conn.unique_name().expect("Unique name").to_string();
    let proxy = Apps1Proxy::builder(&client_conn)
        .destination(server_dest)
        .path(test_path)
        .build()
        .await
        .expect("Build proxy");

    // Launch the application
    proxy
        .launch("sandbox-test.desktop")
        .await
        .expect("Launch must succeed");

    // Wait for dump file
    let mut dumped = false;
    for _ in 0..50 {
        if dump_file.exists() && fs::metadata(&dump_file).unwrap().len() > 0 {
            dumped = true;
            break;
        }
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    assert!(
        dumped,
        "Dump file must be generated by launched application"
    );

    let content = fs::read_to_string(&dump_file).unwrap();
    println!("=== LAUNCHED APP STATUS DUMP ===\n{content}");

    // Parse status fields
    let mut seccomp = None;
    let mut no_new_privs = None;
    let mut ppid: Option<u32> = None;
    let mut umask = None;
    let mut child_pid: Option<u32> = None;

    for line in content.lines() {
        let parts: Vec<&str> = line.split_whitespace().collect();
        if parts.is_empty() {
            continue;
        }
        if parts[0] == "Seccomp:" && parts.len() > 1 {
            seccomp = Some(parts[1].to_string());
        } else if parts[0] == "NoNewPrivs:" && parts.len() > 1 {
            no_new_privs = Some(parts[1].to_string());
        } else if parts[0] == "PPid:" && parts.len() > 1 {
            ppid = parts[1].parse().ok();
        } else if parts[0] == "Umask:" && parts.len() > 1 {
            umask = Some(parts[1].to_string());
        } else if parts[0] == "PID:" && parts.len() > 1 {
            child_pid = parts[1].parse().ok();
        }
    }

    let current_pid = std::process::id();
    assert_eq!(
        seccomp.as_deref(),
        Some("0"),
        "Seccomp filter must be 0 (no sandbox inherited)"
    );
    assert_eq!(no_new_privs.as_deref(), Some("0"), "NoNewPrivs must be 0");
    assert!(
        umask.as_deref() == Some("0002") || umask.as_deref() == Some("0022"),
        "Umask must be user manager default (0002 or 0022), got {:?}",
        umask
    );
    assert_ne!(
        umask.as_deref(),
        Some("0077"),
        "Umask must NOT be daemon's 0077"
    );
    assert!(ppid.is_some(), "PPid must be recorded");
    assert_ne!(
        ppid,
        Some(current_pid),
        "PPid must NOT be the daemon / runner process"
    );

    // Drop server connection simulating daemon exit/crash
    drop(server_conn);
    drop(shared);

    // Verify child process is still alive after daemon drops
    let child_pid = child_pid.expect("Child PID must be parsed");
    let proc_path = format!("/proc/{child_pid}");
    assert!(
        std::path::Path::new(&proc_path).exists(),
        "Launched application (PID {child_pid}) must survive daemon termination"
    );
}
